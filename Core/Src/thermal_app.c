/* ── adc_average ─────────────────────────────────────────────────────────
 *
 *   Collects `n` single ADC conversions via HAL polling and returns the
 *   integer mean.  At 1 Hz with n=128, each sample takes < 20 ms total —
 *   well within the 1000 ms budget.
 *
 *   CubeMX ADC1 prerequisites (MUST match):
 *     - Channel IN0 / PA0
 *     - 12‑bit right‑aligned, single conversion, software trigger
 *     - Scan mode OFF, DMA disabled
 *     - Sampling time: 84 or 144 cycles is fine for a 330 Ω source         */
static uint32_t adc_average(uint8_t n)
{
    uint32_t sum = 0;
    for (uint8_t i = 0; i < n; i++) {
        HAL_ADC_Start(&hadc1);
        if (HAL_ADC_PollForConversion(&hadc1, 10 /*ms timeout*/) == HAL_OK) {
            sum += HAL_ADC_GetValue(&hadc1);
        }
        HAL_ADC_Stop(&hadc1);
    }
    return sum / n;
}

/* ── adc_to_rntc ─────────────────────────────────────────────────────────
 *
 *   Derives R_NTC from the 12‑bit ADC reading.
 *
 *   Divider topology (R_top on TOP from 5.0 V, NTC on BOTTOM to GND):
 *
 *       5.0 V (VSUP)
 *           │
 *         R_top = 330 Ω
 *           │
 *         NODE  ──► PA0 (ADC, reference = THERM_ADC_VREF = 3.3 V)
 *           │
 *         R_NTC ≈ 10 Ω (10D‑9)
 *           │
 *          GND
 *
 *   The ADC measures V_node relative to 3.3 V.  The divider formula is:
 *       R_NTC = R_top × V_node / (VSUP − V_node)
 *   with V_node = 3.3 V × (adc / 4095).  Clamps prevent numerical issues. */
static float adc_to_rntc(uint32_t adc_val)
{
    /* Step 1: ADC counts → node voltage (relative to ADC VREF = 3.3 V) */
    float v = THERM_ADC_VREF * ((float)adc_val / 4095.0f);

    /* Step 2: Clamp low end — avoids divide‑by‑zero in the formula below */
    if (v < 0.001f) v = 0.001f;

    /* Step 3: Clamp high end.
     *   v must be strictly less than VSUP for the denominator (VSUP − v)
     *   to stay positive.  Under normal operation v ≤ THERM_ADC_VREF
     *   (ADC cannot read above its own reference), so the tighter clamp
     *   is simply (THERM_ADC_VREF − ε).                                  */
    float v_max = THERM_DIV_VSUP - 0.001f;
    if (v_max > (THERM_ADC_VREF - 0.001f))
        v_max = THERM_ADC_VREF - 0.001f;
    if (v > v_max) v = v_max;

    /* Step 4: Correct divider formula for VSUP → Rtop → node → Rntc → GND
     *   R_NTC = R_top × V_node / (VSUP − V_node)                        */
    float rntc = THERM_RTOP * (v / (THERM_DIV_VSUP - v));

    /* Step 5: Clamp to physically plausible range for a 10D‑9 */
    if (rntc <    0.1f) rntc =    0.1f;
    if (rntc > 5000.0f) rntc = 5000.0f;

    return rntc;
}

/* ── rntc_to_celsius ─────────────────────────────────────────────────────
 *
 *   Steinhart‑Hart simplified (two‑parameter Beta model):
 *
 *       1/T = 1/T0 + (1/Beta) × ln(R / R0)
 *
 *   ⚠  APPROXIMATE — 10D‑9 is an inrush limiter, not a precision sensor.
 *      Result is monotonic (hotter → lower R → higher T) but absolute
 *      accuracy depends on how well Beta = 3500 K matches your part.
 *      Recalibrate: measure R at 25 °C (R0) and at a second known temp,
 *      then compute  Beta = ln(R1/R2) / (1/T1 − 1/T2).                  */
static float rntc_to_celsius(float rntc)
{
    float inv_T = (1.0f / THERM_T0_K)
                + (1.0f / THERM_BETA) * logf(rntc / THERM_R0);

    /* Guard: prevent division by zero or negative absolute temperature */
    if (inv_T < 1e-6f) inv_T = 1e-6f;

    return (1.0f / inv_T) - 273.15f;   /* Kelvin → Celsius              */
}

/* ── ema_step ────────────────────────────────────────────────────────────
 *   One exponential moving average update.
 *   new_state = old_state + alpha × (new_value − old_state)            */
static inline float ema_step(float state, float value, float alpha)
{
    return state + alpha * (value - state);
}

/* ── pwm_update ──────────────────────────────────────────────────────────
 *
 *   Reads g_duty_cmd (0.0 … 1.0), clamps it, and writes the matching
 *   CCR value to TIM3 CH1.
 *
 *   ARR is read live from the hardware register so this function stays
 *   correct even if you change the CubeMX period setting.
 *
 *   CCR = ARR × duty   (ARR+1 ticks per period, CCR ticks HIGH)        */
static void pwm_update(void)
{
    float cmd = g_duty_cmd;
    if (cmd < -1.0f) cmd = -1.0f;
    if (cmd >  1.0f) cmd =  1.0f;

    uint32_t arr = __HAL_TIM_GET_AUTORELOAD(&htim3);

    float heater_duty;
    float fan_duty;

    if (cmd >= 0.0f) {
        heater_duty = cmd;
        fan_duty    = 0.0f;
    } else {
        heater_duty = 0.0f;
        fan_duty    = -cmd;
    }

    __HAL_TIM_SET_COMPARE(&htim3, TIM_CHANNEL_1,
                          (uint32_t)(heater_duty * (float)arr));
    __HAL_TIM_SET_COMPARE(&htim3, TIM_CHANNEL_2,
                          (uint32_t)(fan_duty * (float)arr));

    g_fan_duty = fan_duty;
}
/* ── log_sample ──────────────────────────────────────────────────────────
 *
 *   Appends one {time, temp, duty} entry to the ring buffer.
 *   Wraps around silently so the log always holds the most recent
 *   THERM_LOG_LEN samples.
 *
 *   To export in STM32CubeIDE debugger:
 *     1. Pause execution.
 *     2. Window → Show View → Memory Browser → type: thermal_log
 *     3. Export Raw Binary, size = THERM_LOG_LEN × 12 = 24576 bytes.
 *     4. Parse in Python:
 *          import numpy as np
 *          d = np.fromfile('thermal.bin', dtype=np.float32).reshape(-1, 3)
 *          # columns: [0] time_s   [1] temp_c   [2] duty               */
static void log_sample(float temp_c, float heater_duty, float fan_duty)
{
    uint32_t idx = thermal_log_idx % THERM_LOG_LEN;

    thermal_log[idx].time_s      = HAL_GetTick() * 0.001f;
    thermal_log[idx].temp_c      = temp_c;
    thermal_log[idx].setpoint_c  = g_setpoint_c;   /* ← add this */
    thermal_log[idx].heater_duty = heater_duty;
    thermal_log[idx].fan_duty    = fan_duty;

    thermal_log_idx++;
}

/* ── format_fixed1 ───────────────────────────────────────────────────────
 *
 *   Formats a float as "±XXX.X" (one decimal place) into buf without
 *   using %f / float printf, so it works even if the linker flag
 *   -u _printf_float is not set.
 *
 *   Returns the number of characters written (not including '\0').
 *
 *   The SSD1306 driver only renders ASCII 32‑90; this function outputs
 *   only digits, '-', and '.', which all fall in that range.           */
static int format_fixed1(char *buf, int buf_len, float val)
{
    int sign = (val < 0.0f) ? 1 : 0;
    if (sign) val = -val;

    int32_t tenths = (int32_t)(val * 10.0f + 0.5f); /* e.g. 25.3 → 253 */
    int32_t whole  = tenths / 10;
    int32_t frac   = tenths % 10;

    if (sign)
        return snprintf(buf, buf_len, "-%ld.%ld", (long)whole, (long)frac);
    else
        return snprintf(buf, buf_len, "%ld.%ld",  (long)whole, (long)frac);
}

/* ── oled_update ─────────────────────────────────────────────────────────
 *
 *   Redraws the full 128×64 OLED dashboard:
 *
 *   ┌──────────────────────────────────┐
 *   │ A:2048  V:1.65                   │  row  0 – ADC avg, node voltage
 *   │ R: 10.0  T: 25.0C               │  row  8 – Rntc, temperature
 *   │ DUTY:  0 PCT                     │  row 16 – heater duty %
 *   ├──────────────────────────────────┤  row 20 – separator line
 *   │                                  │
 *   │   [scrolling temperature plot]   │  rows 22–63  (42 px tall)
 *   │                                  │
 *   └──────────────────────────────────┘
 *
 *   Plot details:
 *     • X axis  : time, oldest left → newest right (128 samples)
 *     • Y axis  : auto‑centered on ema_mean, ±(K × ema_dev) half‑span
 *     • Values  : connected line segments (one Bresenham per pixel step)
 *
 *   NOTE: ssd1306_print() only renders ASCII 32–90.
 *   All strings here use uppercase + digits + common punctuation only.   */
static void oled_update(uint32_t adc_avg, float vnode, float rntc,
                        float temp_c, int duty_pct)
{
    char buf[22];

    ssd1306_clear();

    /* ── Row 0: ADC raw average + node voltage ──────────────────────── */
    {
        char v_str[8];
        format_fixed1(v_str, sizeof(v_str), vnode);
        snprintf(buf, sizeof(buf), "A:%4lu V:%s",
                 (unsigned long)adc_avg, v_str);
    }
    ssd1306_print(0, 0, buf);

    /* ── Row 8: NTC resistance + temperature ───────────────────────── */
    {
        char r_str[8], t_str[8];
        format_fixed1(r_str, sizeof(r_str), rntc);
        format_fixed1(t_str, sizeof(t_str), temp_c);
        snprintf(buf, sizeof(buf), "R:%s T:%sC", r_str, t_str);
    }
    ssd1306_print(0, 8, buf);

    /* ── Row 16: Heater duty ────────────────────────────────────────── */
    snprintf(buf, sizeof(buf), "DUTY:%3d PCT", duty_pct);
    ssd1306_print(0, 16, buf);

    /* ── Separator line ─────────────────────────────────────────────── */
    ssd1306_draw_line(0, 20, 127, 20);

    /* ── Scrolling temperature plot ─────────────────────────────────── *
     *
     *  Auto‑centering / auto‑scaling:
     *
     *   plot_center  = ema_mean  (follows the signal mean slowly)
     *   half_span    = max( K × ema_dev,  MIN_SPAN/2 )
     *
     *  So if ema_dev = 0.5 °C and K = 3:
     *     half_span = 1.5 °C  → plot covers ±1.5 °C = 3 °C full range
     *     A 1 °C change occupies 42 × (1/3) ≈ 14 pixels — very visible.
     *
     *  Mapping (0 = top of OLED):
     *     screen_y = PLOT_BOTTOM − round( (val − plot_min)/span × PLOT_H )
     *
     *  The ring buffer stores the EMA‑filtered temperature so the trace
     *  is already smooth — no further filtering needed here.            */

    const uint8_t PLOT_TOP    = 22;
    const uint8_t PLOT_BOTTOM = 63;
    const uint8_t PLOT_H      = PLOT_BOTTOM - PLOT_TOP;   /* 41 px       */

    float half_span = THERM_PLOT_K * ema_dev;
    if (half_span < THERM_PLOT_MIN_SPAN / 2.0f)
        half_span = THERM_PLOT_MIN_SPAN / 2.0f;

    float plot_min = ema_mean - half_span;
    float span     = 2.0f * half_span;                    /* Always > 0  */

    int32_t prev_y = -1;

    for (uint8_t x = 0; x < THERM_PLOT_LEN; x++) {

        /* Read oldest → newest from the ring buffer.
         * plot_head points to the NEXT write slot, so plot_head is the
         * oldest entry (it was overwritten PLOT_LEN iterations ago).    */
        uint8_t idx = (uint8_t)((plot_head + x) % THERM_PLOT_LEN);
        float val = plot_buf[idx];

        /* Normalise 0..1, clamp */
        float norm = (val - plot_min) / span;
        if (norm < 0.0f) norm = 0.0f;
        if (norm > 1.0f) norm = 1.0f;

        /* Y=0 is top, so higher temperature → lower screen_y */
        int32_t y = (int32_t)PLOT_BOTTOM - (int32_t)(norm * (float)PLOT_H);

        if (prev_y >= 0) {
            ssd1306_draw_line(x - 1, (uint8_t)prev_y, x, (uint8_t)y);
        } else {
            ssd1306_draw_pixel(x, (uint8_t)y, 1);
        }
        prev_y = y;
    }

    ssd1306_update();
}

