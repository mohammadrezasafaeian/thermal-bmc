/* ==========================================================================
 * thermal_app.c  —  Thermal Logger with PID temperature control
 * Target : STM32F411CEU6 "Black Pill" @ 100 MHz  (STM32CubeIDE + HAL)
 *
 * ─── Wiring topology ────────────────────────────────────────────────────
 *
 *   5.0 V (USB) ──┬── R_top = 330 Ω ──┬── NTC 10D‑9 (~10 Ω) ── GND
 *                  │                    │
 *                  │                   PA0 (ADC1_IN0)
 *                  │                   (NODE voltage)
 *
 *   As temperature ↑, R_ntc ↓, so V_node ↑ (approaches 3.3 V).
 *   The ADC reference is 3.3 V; the divider supply is 5.0 V.
 *
 * ─── Heater wiring ─────────────────────────────────────────────────────
 *   PA6 (TIM3_CH1 PWM) → IRLZ44N gate → 10 Ω / 5 W resistor → USB 5 V
 *
 * ─── Module overview ────────────────────────────────────────────────────
 *   ThermalApp_Init()     ← call once after all MX_xxx_Init() in main.c
 *   ThermalApp_Loop()     ← call every iteration of while(1) in main.c
 *
 *   Each loop iteration (~1000 ms):
 *     1. ADC averaging        – 128 conversions polled, averaged
 *     2. Physics              – V_node, R_ntc, T_estimate (Beta model)
 *     3. PID control update   – computes new heater duty (0…1)
 *     4. EMA filters          – smooth display trace + auto‑scale stats
 *     5. Plot ring buffer     – push latest smoothed value
 *     6. PWM update           – write g_duty_cmd → TIM3 CCR1
 *     7. RAM log              – store {time, temp, duty} ring‑buffer entry
 *     8. OLED refresh         – every THERM_OLED_DIVIDER sample(s)
 *     9. Pace                 – HAL_Delay() for the remainder of 1000 ms
 *
 * ─── Debug tip ──────────────────────────────────────────────────────────
 *   Add to Live Expressions:
 *     dbg_adc_avg   – raw 12‑bit ADC average (0–4095)
 *     dbg_vnode     – node voltage measured by ADC (V, 0…3.3)
 *     dbg_rntc      – NTC resistance (Ω)
 *     dbg_temp_c    – raw (unfiltered) temperature estimate (°C)
 *     g_setpoint_c  – desired temperature (°C) – write here to change target
 *     g_duty_cmd    – PID output duty (0.0–1.0)
 *     pid.integral  – PID integrator state
 *     pid.deriv     – PID derivative state
 *     thermal_log_idx – number of log entries written so far
 * ========================================================================== */

