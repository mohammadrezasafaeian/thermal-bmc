/* ── ThermalApp_Init ─────────────────────────────────────────────────────
 *
 *   Call once from main.c after ALL MX_xxx_Init() peripheral inits.
 *
 *   What it does:
 *     • Starts TIM3 PWM output on CH1 (PA6)  — heater starts at 0 %
 *     • Zeroes the plot ring‑buffer and the log buffer
 *     • Shows a brief splash screen on the OLED
 *     • Initialises the PID controller with the tuned gains
 * ------------------------------------------------------------------------ */
/* ==========================================================================
 * PUBLIC API
 * ========================================================================== */
void ThermalApp_Init(void)
{
    /* 1. Clear event queue — must be empty before heartbeat starts */
    RingBuffer_Init();

    /* 2. Start PWM on both channels at 0% duty (safe state)
     *    CubeMX configured the timer but did NOT start it.
     *    We start it here with CCR=0 so the MOSFET gate stays LOW
     *    until the PID deliberately commands a nonzero duty.        */
    HAL_TIM_PWM_Start(&htim3, TIM_CHANNEL_1);       /* heater PA6 */
    __HAL_TIM_SET_COMPARE(&htim3, TIM_CHANNEL_1, 0);
    HAL_TIM_PWM_Start(&htim3, TIM_CHANNEL_2);       /* fan PA7    */
    __HAL_TIM_SET_COMPARE(&htim3, TIM_CHANNEL_2, 0);

    /* 3. Zero display/log state — prevents garbage on first OLED frame */
    memset(plot_buf, 0, sizeof(plot_buf));
    plot_head = 0;
    memset(thermal_log, 0, sizeof(thermal_log));
    thermal_log_idx = 0;

    /* 4. Read initial temperature
     *    Three-stage pipeline: ADC counts → resistance → temperature.
     *    Each function returns a different type, so use matching variables.
     *    This reading seeds PID_Init so the derivative term
     *    doesn't see a false step on the first tick.                   */
    uint32_t adc_raw   = adc_average(THERM_ADC_OVERSAMPLE);
    float    init_rntc = adc_to_rntc(adc_raw);
    float    init_temp = rntc_to_celsius(init_rntc);
    pid_temp = init_temp;
    /* 5. Initialise PID — gains from #defines in thermal_app.h */
    PID_Init(&pid, PID_KP, PID_KI, PID_KD,
             PID_TS, PID_TAU_F, init_temp);

    /* 6. Splash screen — visual proof that init completed */
    ssd1306_clear();
    ssd1306_print(0, 0, "THERMAL CTRL");
    ssd1306_print(0, 16, "V0.6 INIT OK");
    ssd1306_update();
    HAL_Delay(800);

    /* 7. Start 1 Hz heartbeat — MUST BE LAST
     *    From this moment, TIM2 ISR fires every 1s and pushes
     *    EVT_PID_TICK into the ring buffer.  Everything above
     *    must be ready before this line.                          */
    HAL_TIM_Base_Start_IT(&htim2);
}
void ThermalApp_Loop(void) // <--- FIXED: No arguments needed yet
{
    Event_t current_event; // <--- DECLARE THE EVENT VARIABLE

    // --- STEP 1: SENSING (Always Run) ---
    uint32_t adc_avg = adc_average(THERM_ADC_OVERSAMPLE);
    float vnode = THERM_ADC_VREF * ((float)adc_avg / 4095.0f);
    float rntc = adc_to_rntc(adc_avg);
    float temp_c = rntc_to_celsius(rntc);

    // Update debug globals
    dbg_adc_avg = adc_avg;
    dbg_vnode = vnode;
    dbg_rntc = rntc;
    dbg_temp_c = temp_c;

    // --- STEP 2: EVENT PROCESSING (The New Engine) ---
    // Drain the queue. If multiple ticks piled up, process them all.
    while (RingBuffer_Pop(&current_event)) // <--- FIXED: Pass address (&)
    {
        switch (current_event) // <--- FIXED: C syntax with parentheses
        {
        case EVT_PID_TICK:
            // Filter temp before PID sees it
            pid_temp = pid_temp + 0.02f * (temp_c - pid_temp);

                // PID now sees filtered temperature
                g_duty_cmd = PID_Update(&pid, g_setpoint_c, pid_temp);

                // 2. Update EMA Filters (Copied from old loop)
                if (!ema_initialized) {
                    ema_temp_display = temp_c;
                    ema_mean         = temp_c;
                    ema_dev          = 1.0f;
                    ema_initialized  = 1;
                } else {
                    ema_temp_display = ema_step(ema_temp_display, temp_c, THERM_EMA_DISPLAY);
                    ema_mean = ema_step(ema_mean, ema_temp_display, THERM_EMA_MEAN);

                    float abs_dev = ema_temp_display - ema_mean;
                    if (abs_dev < 0.0f) abs_dev = -abs_dev;
                    ema_dev = ema_step(ema_dev, abs_dev, THERM_EMA_DEV);
                    if (ema_dev < 0.05f) ema_dev = 0.05f;
                }

                // 3. Update Plot Buffer
                plot_buf[plot_head] = ema_temp_display;
                plot_head = (uint8_t)((plot_head + 1) % THERM_PLOT_LEN);

                // 4. Log Data
                log_sample(ema_temp_display, g_duty_cmd, g_fan_duty);
                break; // <--- CRITICAL: Don't fall through to other cases!

            case EVT_START_CMD:
                // Optional: Handle manual start later
                break;

            case EVT_STOP_CMD:
                // Optional: Handle stop later
                break;

            default:
                break;
        }
    }

    // --- STEP 3: ACTUATION (Always Run) ---
    // Update PWM to reflect latest g_duty_cmd
    pwm_update();

    // --- STEP 4: UI (Always Run, Throttled) ---
    static uint8_t oled_div = 0;
    oled_div++;
    if (oled_div >= THERM_OLED_DIVIDER) {
        oled_div = 0;
        int duty_pct = (int)(g_duty_cmd * 100.0f + 0.5f);
        if (duty_pct < 0) duty_pct = 0;
        if (duty_pct > 100) duty_pct = 100;

        oled_update(adc_avg, vnode, rntc, ema_temp_display, duty_pct);
    }

    // --- STEP 5: TIMING ---
    // The HAL_Delay is GONE. The loop runs as fast as possible.
    // The PID is paced by the Timer Interrupt, not by this loop.
}
